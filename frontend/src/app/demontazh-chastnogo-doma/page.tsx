const EQUIPMENT_MATCH_RULES: Array<{ token: string; score: number }> = [
  { token: "демонтаж", score: 14 },
  { token: "снос", score: 12 },
  { token: "экскаватор", score: 10 },
  { token: "гидромолот", score: 10 },
  { token: "погрузчик", score: 9 },
  { token: "самосвал", score: 12 },
  { token: "строительный мусор", score: 8 },
  { token: "бетон", score: 7 },
  { token: "кирпич", score: 6 },
  { token: "фундамент", score: 7 },
];

function normalizeText(value: string | null | undefined) {
  if (!value) return "";
  return value.toLocaleLowerCase("ru-RU").replace(/ё/g, "е").replace(/\s+/g, " ").trim();
}

function itemSearchSource(item: EquipmentCardRecord) {
  const equipmentTypes = (item.equipment_types || []).map((entry) => normalizeText(entry.name)).join(" ");
  const workTypes = (item.work_types || []).map((entry) => normalizeText(entry.name)).join(" ");

  return `${normalizeText(item.title)} ${normalizeText(item.excerpt)} ${equipmentTypes} ${workTypes}`;
}

function scoreEquipment(item: EquipmentCardRecord) {
  const source = itemSearchSource(item);
  let score = 0;

  for (const rule of EQUIPMENT_MATCH_RULES) {
    if (source.includes(rule.token)) score += rule.score;
  }

  if (source.includes("самосвал") && (source.includes("мусор") || source.includes("бой"))) score += 6;
  if (source.includes("экскаватор") && source.includes("демонтаж")) score += 6;
  if (source.includes("гидромолот") && source.includes("бетон")) score += 5;

  return score;
}

function isDumpItem(item: EquipmentCardRecord) {
  return itemSearchSource(item).includes("самосвал");
}

function isDemolitionItem(item: EquipmentCardRecord) {
  const source = itemSearchSource(item);
  return source.includes("экскаватор") || source.includes("гидромолот") || source.includes("погрузчик");
}

function pickRelevantEquipment(items: EquipmentCardRecord[]) {
  const ranked = items
    .map((item) => ({ item, score: scoreEquipment(item) }))
    .filter((entry) => entry.score > 0)
    .sort((left, right) => {
      const scoreDelta = right.score - left.score;
      if (scoreDelta !== 0) return scoreDelta;
      return left.item.title.localeCompare(right.item.title, "ru-RU");
    })
    .map((entry) => entry.item);

  if (!ranked.length) {
    return items.filter((item) => /экскаватор|погрузчик|самосвал|гидромолот/iu.test(item.title)).slice(0, MAX_EQUIPMENT_ITEMS);
  }

  const selected = ranked.slice(0, MAX_EQUIPMENT_ITEMS);
  const selectedIds = new Set(selected.map((item) => item.id));

  const ensureItemType = (predicate: (item: EquipmentCardRecord) => boolean, minimumCount: number) => {
    let currentCount = selected.filter(predicate).length;
    if (currentCount >= minimumCount) return;

    const replaceableIndexes = selected
      .map((item, index) => ({ item, index }))
      .filter((entry) => !predicate(entry.item))
      .map((entry) => entry.index)
      .reverse();

    for (const candidate of ranked) {
      if (currentCount >= minimumCount) break;
      if (selectedIds.has(candidate.id) || !predicate(candidate)) continue;

      const replaceIndex = replaceableIndexes.shift();
      if (replaceIndex === undefined) break;

      selectedIds.delete(selected[replaceIndex].id);
      selected[replaceIndex] = candidate;
      selectedIds.add(candidate.id);
      currentCount += 1;
    }
  };

  ensureItemType(isDumpItem, MIN_DUMP_ITEMS);
  ensureItemType(isDemolitionItem, MIN_DEMOLITION_ITEMS);

  return selected;
}

