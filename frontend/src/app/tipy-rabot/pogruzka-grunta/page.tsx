function normalizeText(value: string | null | undefined) {
  if (!value) return "";
  return value
    .toLocaleLowerCase("ru-RU")
    .replace(/ё/g, "е")
    .replace(/\s+/g, " ")
    .trim();
}

function scoreEquipment(item: EquipmentCardRecord) {
  const title = normalizeText(item.title);
  const excerpt = normalizeText(item.excerpt);
  const equipmentTypes = (item.equipment_types || []).map((entry) => normalizeText(entry.name)).join(" ");
  const workTypes = (item.work_types || []).map((entry) => normalizeText(entry.name)).join(" ");
  const source = `${title} ${excerpt} ${equipmentTypes} ${workTypes}`;

  let score = 0;

  for (const rule of EQUIPMENT_MATCH_RULES) {
    if (source.includes(rule.token)) score += rule.score;
  }

  if (title.includes("экскаватор") && source.includes("грунт")) {
    score += 6;
  }

  if ((source.includes("погруз") || source.includes("погрузка")) && source.includes("самосвал")) {
    score += 6;
  }

  return score;
}

function pickRelevantEquipment(items: EquipmentCardRecord[]) {
  const ranked = items
    .map((item) => ({ item, score: scoreEquipment(item) }))
    .filter((entry) => entry.score > 0)
    .sort((left, right) => {
      const scoreDelta = right.score - left.score;
      if (scoreDelta !== 0) return scoreDelta;
      return left.item.title.localeCompare(right.item.title, "ru-RU");
    })
    .map((entry) => entry.item);

  if (ranked.length) {
    return ranked.slice(0, MAX_EQUIPMENT_ITEMS);
  }

  const fallbackByTitle = items.filter((item) => /экскаватор|погрузчик|самосвал|фронтальн/iu.test(item.title));
  if (fallbackByTitle.length) {
    return fallbackByTitle.slice(0, MAX_EQUIPMENT_ITEMS);
  }

  return items.slice(0, MAX_EQUIPMENT_ITEMS);
}

