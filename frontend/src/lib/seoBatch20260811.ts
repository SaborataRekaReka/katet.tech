export function seoBatchIllustrationByUrlPath(urlPath: string | null | undefined) {
  if (!urlPath) return null;
  const normalized = urlPath.endsWith("/") ? urlPath : `${urlPath}/`;
  return Object.values(SEO_BATCH_SERVICES).find((service) => service.urlPath === normalized)?.heroImage || null;
}

function escapeHtml(value: string) {
  return value.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/\"/g, "&quot;");
}

